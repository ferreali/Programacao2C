'''Cada caractere possui um índice que começa em 0:'''
palavra = "Python"
# Índices:  0    1    2    3    4    5
#          'P'  'y'  't'  'h'  'o'  'n'

print(palavra[0])   # Saída: P
print(palavra[5])   # Saída: n
print(palavra[-1])  # Saída: n (último caractere)
print(palavra[-2])  # Saída: o (penúltimo)